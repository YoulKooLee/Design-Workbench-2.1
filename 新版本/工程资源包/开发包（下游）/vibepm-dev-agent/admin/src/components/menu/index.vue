<script lang="tsx">
  import {
    defineComponent,
    ref,
    h,
    compile,
    computed,
    resolveComponent,
    inject,
    type Ref,
  } from 'vue';
  import { useI18n } from 'vue-i18n';
  import { useRoute, useRouter, RouteRecordRaw } from 'vue-router';
  import type { RouteMeta } from 'vue-router';
  import { useAppStore } from '@/store';
  import { listenerRouteChange } from '@/utils/route-listener';
  import { openWindow, regexUrl } from '@/utils';
  import useMenuTree from './use-menu-tree';

  export default defineComponent({
    emit: ['collapse'],
    setup() {
      const { t } = useI18n();
      const appStore = useAppStore();
      const router = useRouter();
      const route = useRoute();
      const { menuTree } = useMenuTree();
      const closeMobileMenu = inject('closeMobileMenu', () => undefined);
      const isNarrowShell = inject<Ref<boolean>>('isNarrowShell', ref(false));
      const collapsed = computed({
        get() {
          if (isNarrowShell.value) return false;
          return appStore.menuCollapse;
        },
        set(value: boolean) {
          if (isNarrowShell.value) {
            closeMobileMenu();
            return;
          }
          appStore.updateSettings({ menuCollapse: value });
        },
      });

      const topMenu = computed(() => appStore.topMenu);
      const openKeys = ref<string[]>([]);
      const selectedKey = ref<string[]>([]);

      const goto = (item: RouteRecordRaw) => {
        // Open external link
        if (regexUrl.test(item.path)) {
          openWindow(item.path);
          selectedKey.value = [item.name as string];
          return;
        }
        // Eliminate external link side effects
        const { hideInMenu, activeMenu } = item.meta as RouteMeta;
        if (route.name === item.name && !hideInMenu && !activeMenu) {
          selectedKey.value = [item.name as string];
          return;
        }
        // Trigger router change
        router.push({
          name: item.name,
        });
      };
      const findMenuOpenKeys = (target: string) => {
        const result: string[] = [];
        let isFind = false;
        const backtrack = (item: RouteRecordRaw, keys: string[]) => {
          if (item.name === target) {
            isFind = true;
            result.push(...keys);
            return;
          }
          if (item.children?.length) {
            item.children.forEach((el) => {
              backtrack(el, [...keys, el.name as string]);
            });
          }
        };
        menuTree.value.forEach((el: RouteRecordRaw) => {
          if (isFind) return; // Performance optimization
          backtrack(el, [el.name as string]);
        });
        return result;
      };
      listenerRouteChange((newRoute) => {
        const { requiresAuth, activeMenu, hideInMenu } = newRoute.meta;
        if (requiresAuth && (!hideInMenu || activeMenu)) {
          const menuOpenKeys = findMenuOpenKeys(
            (activeMenu || newRoute.name) as string
          );

          // Align with master: only keep ancestors of the active item
          // (collapse other top-level categories on navigate/select).
          openKeys.value = [...menuOpenKeys];

          selectedKey.value = [
            activeMenu || menuOpenKeys[menuOpenKeys.length - 1],
          ];
        }
      }, true);
      const setCollapse = (val: boolean) => {
        if (isNarrowShell.value) {
          closeMobileMenu();
          return;
        }
        appStore.updateSettings({ menuCollapse: val });
      };

      const renderSubMenu = () => {
        function travel(_route: RouteRecordRaw[], nodes = []) {
          if (_route) {
            _route.forEach((element) => {
              // This is demo, modify nodes as needed
              const iconName = element?.meta?.icon as string | undefined;
              const icon = iconName
                ? () =>
                    h(resolveComponent(iconName), {
                      class: 'pro-menu-item-icon',
                      size: collapsed.value ? 16 : 14,
                    })
                : null;
              const node =
                element?.children && element?.children.length !== 0 ? (
                  <a-sub-menu
                    key={element?.name}
                    v-slots={{
                      icon,
                      title: () => h(compile(t(element?.meta?.locale || ''))),
                    }}
                  >
                    {travel(element?.children)}
                  </a-sub-menu>
                ) : (
                  <a-menu-item
                    key={element?.name}
                    v-slots={{ icon }}
                    onClick={() => goto(element)}
                  >
                    {t(element?.meta?.locale || '')}
                  </a-menu-item>
                );
              nodes.push(node as never);
            });
          }
          return nodes;
        }
        return travel(menuTree.value);
      };

      const renderFaIcon = (name: string, className: string, size: number) =>
        h(resolveComponent(name), { class: className, size });

      return () => (
        <a-menu
          class="pro-sider-menu"
          mode={topMenu.value ? 'horizontal' : 'vertical'}
          v-model:collapsed={collapsed.value}
          v-model:open-keys={openKeys.value}
          show-collapse-button={true}
          auto-open={false}
          selected-keys={selectedKey.value}
          auto-open-selected={true}
          level-indent={34}
          style="height: 100%;width:100%;"
          onCollapse={setCollapse}
          v-slots={{
            default: () => renderSubMenu(),
            'expand-icon-down': () =>
              renderFaIcon('icon-down', 'pro-menu-arrow-icon', 10),
            'expand-icon-right': () =>
              renderFaIcon('icon-right', 'pro-menu-arrow-icon', 10),
            'collapse-icon': ({
              collapsed: menuCollapsed,
            }: {
              collapsed?: boolean;
            }) =>
              renderFaIcon(
                menuCollapsed ? 'icon-menu-unfold' : 'icon-menu-fold',
                'pro-menu-collapse-icon',
                14
              ),
          }}
        />
      );
    },
  });
</script>

