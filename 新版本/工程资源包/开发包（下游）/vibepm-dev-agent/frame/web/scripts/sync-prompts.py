# -*- coding: utf-8 -*-
"""
全局：按 catalog.families[] 将成员 prompt.md 打成家族根目录的 prompts.inline.js
（供 file:// 下复制；HTTP 家族页可直接 fetch 子目录 prompt.md，不必生成）

用法（在 frame/web 下）：
  python scripts/sync-prompts.py              # 同步全部 families
  python scripts/sync-prompts.py date-picker  # 只同步一个 family slug
"""
from __future__ import annotations

from catalog_io import load_catalog

import json
import sys
from pathlib import Path

WEB = Path(__file__).resolve().parents[1]


def component_path_by_slug(catalog: dict, slug: str) -> Path | None:
    for item in catalog.get("components") or []:
        if item.get("slug") == slug:
            rel = item.get("path") or f"components/{slug}"
            return WEB / rel
    return None


def sync_family(catalog: dict, family: dict) -> Path:
    fam_slug = family.get("slug") or ""
    fam_rel = family.get("path") or f"components/{fam_slug}"
    fam_dir = WEB / fam_rel
    if not fam_dir.is_dir():
        raise SystemExit(f"[skip] family dir missing: {fam_rel}")

    members = family.get("members") or []
    if not members:
        raise SystemExit(f"[skip] family {fam_slug} has no members")

    prompts: dict[str, str] = {}
    for slug in members:
        member_dir = component_path_by_slug(catalog, slug)
        if not member_dir:
            raise SystemExit(f"member slug not in catalog.components: {slug}")
        prompt_file = member_dir / "prompt.md"
        if not prompt_file.is_file():
            raise SystemExit(f"missing {prompt_file.relative_to(WEB)}")
        prompts[slug] = prompt_file.read_text(encoding="utf-8-sig").replace("\r\n", "\n")

    payload = json.dumps(prompts, ensure_ascii=False, indent=2)
    js = (
        "/* Auto-generated by scripts/sync-prompts.py — do not edit by hand */\n"
        "window.WA_FAMILY_PROMPTS = "
        + payload
        + ";\n"
    )
    out = fam_dir / "prompts.inline.js"
    out.write_bytes(b"\xef\xbb\xbf" + js.encode("utf-8"))
    print(f"ok {out.relative_to(WEB).as_posix()} ({len(prompts)} prompts, {out.stat().st_size} bytes)")
    return out


def main(argv: list[str]) -> int:
    catalog = load_catalog()
    families = catalog.get("families") or []
    if not families:
        print("no families[] in catalog")
        return 1

    only = argv[1] if len(argv) > 1 else None
    matched = 0
    for fam in families:
        if only and fam.get("slug") != only:
            continue
        sync_family(catalog, fam)
        matched += 1

    if only and matched == 0:
        print(f"family not found: {only}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
